import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const migrationDir = resolve('drizzle');
const migrationFiles = readdirSync(migrationDir).filter((name) => name.endsWith('.sql')).sort();
if (migrationFiles.length === 0) throw new Error('No Drizzle migration found. Run npm run db:generate first.');
const statements = migrationFiles.flatMap((name) => readFileSync(resolve(migrationDir,name),'utf8')
  .split('--> statement-breakpoint')
  .map((statement) => statement.trim()
    .replace(/^CREATE TABLE /,'CREATE TABLE IF NOT EXISTS ')
    .replace(/^CREATE INDEX /,'CREATE INDEX IF NOT EXISTS ')
    .replace(/^CREATE UNIQUE INDEX /,'CREATE UNIQUE INDEX IF NOT EXISTS '))
  .filter(Boolean));
const output = `// Generated by scripts/embed-migration.mjs. Do not edit by hand.\nexport const schemaStatements: readonly string[] = ${JSON.stringify(statements,null,2)};\n`;
writeFileSync(resolve('db/runtime-schema.ts'),output);
console.log(`Embedded ${statements.length} migration statements from ${migrationFiles.length} file.`);
